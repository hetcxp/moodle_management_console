// Robust config.php locator supporting symlinked plugin directory.
$config_paths = [
    __DIR__ . '/../../../config.php',
];
if (isset($_SERVER['SCRIPT_FILENAME'])) {
    $config_paths[] = dirname(dirname(dirname($_SERVER['SCRIPT_FILENAME']))) . '/config.php';
    $config_paths[] = dirname(dirname(dirname(dirname($_SERVER['SCRIPT_FILENAME'])))) . '/config.php';
    $config_paths[] = dirname(dirname(dirname(dirname($_SERVER['SCRIPT_FILENAME'])))) . '/../config.php';
}
if (isset($_SERVER['DOCUMENT_ROOT'])) {
    $config_paths[] = $_SERVER['DOCUMENT_ROOT'] . '/../config.php';
    $config_paths[] = $_SERVER['DOCUMENT_ROOT'] . '/config.php';
}
$config_loaded = false;
foreach ($config_paths as $config_path) {
    if (file_exists($config_path)) {
        require_once($config_path);
        $config_loaded = true;
        break;
    }
}
if (!$config_loaded) {
    die('Failed to locate Moodle config.php for tool_management_console.');
}

// 1. Auth + capability check.
require_login();
$context = context_system::instance();
require_capability('tool/management_console:access', $context);

// 2. Page setup — embedded = fullscreen, sin sidebar Moodle.
$PAGE->set_url(new moodle_url('/admin/tool/management_console/index.php'));
$PAGE->set_context($context);
$PAGE->set_pagelayout('embedded');
$PAGE->set_title(get_string('pluginname', 'tool_management_console'));

// 3. Generar wstoken para el usuario actual.
global $DB, $USER, $CFG, $OUTPUT;
$service = $DB->get_record('external_services', ['shortname' => 'management_console_service']);
if (!$service) {
    http_response_code(503);
    header('Content-Type: text/html; charset=utf-8');
    die('<html lang="es"><body style="font-family:sans-serif;padding:2rem;max-width:600px;margin:auto">
        <h1>Servicio no disponible</h1>
        <p>El servicio web <code>management_console_service</code> no está habilitado en Moodle.</p>
        <p>Ve a <strong>Administración → Servidor → Servicios web → Servicios externos</strong> y activa el servicio.</p>
    </body></html>');
}
// Buscar token existente o crear uno nuevo con validez acotada (8 horas de sesión).
$validuntil = time() + (8 * 3600);
$tokentype = defined('EXTERNAL_TOKEN_PERMANENT') ? EXTERNAL_TOKEN_PERMANENT : 0;
if (class_exists('\core_external\util') && method_exists('\core_external\util', 'generate_token')) {
    $token = \core_external\util::generate_token(
        $tokentype,
        $service,
        $USER->id,
        $context,
        $validuntil
    );
} else {
    require_once($CFG->libdir . '/externallib.php');
    $token = external_generate_token(
        $tokentype,
        $service,
        $USER->id,
        $context,
        $validuntil
    );
}

// 4. Deterministic asset discovery: parse canonical index.html generated by Vite.
$appindex = __DIR__ . '/app/index.html';
$appdir   = __DIR__ . '/app/assets';
$cssfile  = '';
$jsfile   = '';

if (file_exists($appindex)) {
    $htmlcontent = file_get_contents($appindex);
    if (preg_match('/<script[^>]+src=["\'][^"\']*assets\/([^"\']+\.js)["\']/i', $htmlcontent, $m)) {
        $jsfile = $m[1];
    }
    if (preg_match('/<link[^>]+href=["\'][^"\']*assets\/([^"\']+\.css)["\']/i', $htmlcontent, $m)) {
        $cssfile = $m[1];
    }
}

// Security TD-OPS-001: Fail-closed on missing or invalid canonical assets.
if (!$jsfile || !$cssfile || !file_exists($appdir . '/' . $jsfile) || !file_exists($appdir . '/' . $cssfile)) {
    http_response_code(503);
    header('Content-Type: text/html; charset=utf-8');
    echo '<!DOCTYPE html>
<html lang="es">
<head>
    <meta charset="utf-8">
    <title>Application Build Error</title>
    <style>
        body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
               padding: 2rem; text-align: center; background: #f8fafc; color: #1e293b; }
    </style>
</head>
<body>
    <h1>Error de interfaz SPA</h1>
    <p>Los artefactos compilados canónicos no están disponibles. ' .
       'Ejecute <code>npm run build:moodle</code> para regenerarlos.</p>
</body>
</html>';
    exit;
}

// 5. Render: We skip $OUTPUT->header() to avoid Moodle CSS interfering.
$nonce = base64_encode(random_bytes(16));
$csp = "default-src 'self'; script-src 'self' 'nonce-{$nonce}' https://fonts.googleapis.com; " .
       "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; img-src 'self' data: blob: https: http:;";
header("Content-Security-Policy: {$csp}");
header('Content-Type: text/html; charset=utf-8');
header('Cache-Control: no-cache, no-store, must-revalidate');
header('Pragma: no-cache');
header('Expires: 0');

echo '<!DOCTYPE html>
<html lang="es">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>' . get_string('pluginname', 'tool_management_console') . '</title>';

// Inyectar CSS.
if ($cssfile) {
    echo '<link rel="stylesheet" href="' .
         (new moodle_url("/admin/tool/management_console/app/assets/{$cssfile}"))->out() . '">';
}

$userinfo = [
    'userid'    => (int)$USER->id,
    'username'  => $USER->username,
    'fullname'  => fullname($USER),
    'firstname' => $USER->firstname,
    'lastname'  => $USER->lastname,
];
$moodleurl = $CFG->wwwroot;
if (is_https() && str_starts_with($moodleurl, 'http://')) {
    $moodleurl = 'https://' . substr($moodleurl, 7);
}

$enablefeedback = get_config('tool_management_console', 'enable_feedback');
$feedbackenabled = ($enablefeedback === false || (string)$enablefeedback !== '0');

// Inyectar config JS global (ANTES del bundle) con escape contextual estricto.
$jsonflags = JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT;
$basepath = (new moodle_url('/admin/tool/management_console/index.php'))->out_as_local_url(false);
echo "<script nonce=\"{$nonce}\">\n";
echo "window.MANAGEMENT_CONSOLE_CONFIG = {\n";
echo "    token: " . json_encode($token, $jsonflags) . ",\n";
echo "    moodleUrl: " . json_encode($moodleurl, $jsonflags) . ",\n";
echo "    serviceName: \"management_console_service\",\n";
echo "    basePath: " . json_encode($basepath, $jsonflags) . ",\n";
echo "    embedded: true,\n";
echo "    feedbackEnabled: " . json_encode($feedbackenabled, $jsonflags) . ",\n";
echo "    user: " . json_encode($userinfo, $jsonflags) . "\n";
echo "};\n";
echo "window.ADMINER_CONFIG = window.MANAGEMENT_CONSOLE_CONFIG;\n";
echo "</script>";

// Google Fonts.
echo '<link rel="preconnect" href="https://fonts.googleapis.com">';
echo '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>';
$fonturl = 'https://fonts.googleapis.com/css2?' .
           'family=Plus+Jakarta+Sans:wght@400;500;600;700;800&' .
           'family=JetBrains+Mono:wght@400;500&display=swap';
echo '<link href="' . $fonturl . '" rel="stylesheet">';

// TD-PERF-002: Preload strictly the entry module, not all lazy chunks.
if ($jsfile) {
    echo '<link rel="modulepreload" href="' .
         (new moodle_url("/admin/tool/management_console/app/assets/{$jsfile}"))->out() . '">';
}

echo '</head>
<body>
    <noscript>
      <div style="font-family:sans-serif;padding:2rem;text-align:center">
        <p>Esta aplicación requiere JavaScript. Por favor habilítalo en tu navegador.</p>
      </div>
    </noscript>
    <div id="root"></div>';

// Bundle JS principal.
if ($jsfile) {
    echo '<script type="module" src="' .
         (new moodle_url("/admin/tool/management_console/app/assets/{$jsfile}"))->out() . '"></script>';
}

echo '</body>
</html>';
